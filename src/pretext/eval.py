# Held-out-site probe is the headline. Same-site is debug. No invented %.

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from . import const, probe, ssl


def check_no_leak(train_sites, test_sites) -> None:
    """Fail if a held-out site image sits in the SSL / probe train pool."""
    overlap = set(train_sites) & set(test_sites)
    if overlap:
        raise ValueError(f"leak: held-out sites {sorted(overlap)} in train pool")


def site_split(sites: np.ndarray, test_site: str):
    train = np.where(sites != test_site)[0]
    test = np.where(sites == test_site)[0]
    check_no_leak(sites[train], sites[test])
    return train, test


def evaluate(
    bundle: dict,
    test_site: str = const.TEST_SITE,
    ssl_epochs: int = const.SSL_EPOCHS,
    sup_epochs: int = const.SUPERVISED_EPOCHS,
    seed: int = const.SEED,
) -> dict:
    images, y, sites = bundle["images"], bundle["y"], bundle["site"]
    classes = [str(c) for c in bundle["classes"]]
    train_idx, test_idx = site_split(sites, test_site)
    n_classes = len(classes)
    chance = 100.0 / n_classes

    enc = ssl.pretrain(images[train_idx], epochs=ssl_epochs, seed=seed)
    z_all = ssl.embed(enc, images)
    z_tr, y_tr = z_all[train_idx], y[train_idx]
    z_te, y_te = z_all[test_idx], y[test_idx]

    clf = probe.fit_probe(z_tr, y_tr, seed=seed)
    success = probe.probe_pct(clf, z_te, y_te)

    rng = np.random.default_rng(seed)
    perm = rng.permutation(len(train_idx))
    cut = max(int(0.8 * len(perm)), 1)
    same_tr, same_te = train_idx[perm[:cut]], train_idx[perm[cut:]]
    clf_same = probe.fit_probe(z_all[same_tr], y[same_tr], seed=seed)
    same_site = probe.probe_pct(clf_same, z_all[same_te], y[same_te]) if len(same_te) else success

    rand_enc = ssl.random_encoder(seed=seed + 1)
    zr = ssl.embed(rand_enc, images)
    clf_r = probe.fit_probe(zr[train_idx], y[train_idx], seed=seed)
    random_pct = probe.probe_pct(clf_r, zr[test_idx], y[test_idx])

    supervised = probe.supervised_pct(
        images[train_idx],
        y[train_idx],
        images[test_idx],
        y[test_idx],
        n_classes,
        epochs=sup_epochs,
        seed=seed,
    )

    train_sites = sorted(set(sites[train_idx].tolist()))
    test_sites = sorted(set(sites[test_idx].tolist()))
    return {
        "success_pct": success,
        "probe_pct": success,
        "same_site_pct": same_site,
        "supervised_pct": supervised,
        "random_encoder_pct": random_pct,
        "chance_pct": chance,
        "n_sites_train": len(train_sites),
        "n_sites_test": len(test_sites),
        "n_train": int(len(train_idx)),
        "n_test": int(len(test_idx)),
        "n_classes": n_classes,
        "classes": classes,
        "train_sites": train_sites,
        "test_sites": test_sites,
        "test_site": test_site,
        "ssl_epochs": ssl_epochs,
        "illustrative": False,
    }


def print_report(m: dict) -> None:
    tag = "ILLUSTRATIVE" if m.get("illustrative") else "measured"
    print(
        f"probe_pct {m['probe_pct']:.1f}  |  same_site_pct {m['same_site_pct']:.1f}  "
        f"|  supervised_pct {m['supervised_pct']:.1f}  |  random_encoder_pct {m['random_encoder_pct']:.1f}  "
        f"|  chance_pct {m['chance_pct']:.1f}  [{tag}]"
    )
    print(
        f"success_pct {m['success_pct']:.1f}  n_sites_train {m['n_sites_train']}  "
        f"n_sites_test {m['n_sites_test']}  n_classes {m['n_classes']}  test_site {m['test_site']}"
    )


def write_metrics(m: dict, path: str = const.METRICS_PATH) -> None:
    Path(path).write_text(json.dumps(m, indent=2), encoding="utf-8")


